"""Modular Teacher LLM interface for VAULT.

Supports:
1. 'endpoint' mode: Calls an external or separate-compute inference server (e.g., vLLM/Ollama).
2. 'fixture' mode: Offline deterministic synthetic generator consuming truth-ledger records,
   explicitly labeled as non-LLM generation.
3. Local 8B hardware guard: Refuses to load an 8B teacher model on <=6 GB VRAM to prevent OOM.
"""
from __future__ import annotations

import hashlib
import json
import time
import urllib.error
import urllib.request
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Literal, Optional

from .artifacts import fingerprint, now, write_json

TEACHER_MODEL_ID = "CohereLabs/aya-expanse-8b"
TEACHER_REVISION = "5062468bf9bc0c6035fd64e06274333ec127d980"
TEACHER_LICENSE = "CC-BY-NC-4.0"
TEACHER_PROMPT_VERSION = "vault-teacher-v1"


@dataclass(frozen=True)
class TruthLedgerRecord:
    """Authoritative scientific record from Vijay's verifier/truth ledger."""
    ledger_id: str
    scenario_family: str
    experiment_id: str
    measurand: str
    verified_value: Optional[float]
    unit: Optional[str]
    decision: str  # e.g., 'pass', 'flagged', 'inconclusive'
    evidence_text: str
    source_id: str
    sop_version: str
    assumptions: List[str] = field(default_factory=list)


@dataclass
class TeacherOutput:
    """Structured candidate generated by the teacher interface."""
    record_id: str
    ledger_id: str
    scenario_family: str
    candidate_question: str
    lab_notes: str
    explanation: str
    evidence_spans: List[str]
    source_ids: List[str]
    target_response: Dict[str, Any]
    metadata: Dict[str, Any]
    content_hash: str


class TeacherHardwareError(RuntimeError):
    """Raised when local hardware cannot hold the teacher model."""
    pass


class TeacherClient:
    """Modular teacher client for dataset synthesis."""

    def __init__(
        self,
        mode: Literal["fixture", "endpoint"] = "fixture",
        endpoint_url: Optional[str] = None,
        api_key: Optional[str] = None,
        max_retries: int = 3,
        timeout_seconds: float = 30.0,
        model_id: str = TEACHER_MODEL_ID,
        revision: str = TEACHER_REVISION,
    ):
        self.mode = mode
        self.endpoint_url = endpoint_url
        self.api_key = api_key
        self.max_retries = max_retries
        self.timeout_seconds = timeout_seconds
        self.model_id = model_id
        self.revision = revision

    @staticmethod
    def verify_local_hardware_budget():
        """Assert that an 8B teacher model cannot run on <=6 GB VRAM alongside student weights."""
        try:
            import torch
            if torch.cuda.is_available():
                total_vram_gb = torch.cuda.get_device_properties(0).total_memory / (1024 ** 3)
                if total_vram_gb < 14.0:
                    raise TeacherHardwareError(
                        f"Local GPU has {total_vram_gb:.2f} GB VRAM. Cohere Aya Expanse 8B requires >=14 GB VRAM "
                        "(or >=6 GB dedicated solely to teacher in NF4 without the 3.35B student). "
                        "Use mode='fixture' for deterministic offline synthesis or mode='endpoint' "
                        "pointing to separate permitted compute."
                    )
        except ImportError:
            pass

    def generate_candidate(self, truth_record: TruthLedgerRecord) -> TeacherOutput:
        """Generate structured candidate question, context, and explanation from a verified truth record."""
        if self.mode == "fixture":
            return self._generate_fixture(truth_record)
        elif self.mode == "endpoint":
            return self._generate_endpoint(truth_record)
        else:
            raise ValueError(f"Unsupported teacher mode: {self.mode}")

    def _generate_fixture(self, truth_record: TruthLedgerRecord) -> TeacherOutput:
        """Deterministic offline generation based on authoritative truth records."""
        # Synthesize a realistic laboratory question based on the scenario family
        family = truth_record.scenario_family
        measurand_readable = truth_record.measurand.replace("_", " ")

        if truth_record.decision == "pass":
            question = (
                f"Based on the verification of {truth_record.experiment_id}, what is the confirmed "
                f"{measurand_readable} under {truth_record.sop_version}?"
            )
            explanation = (
                f"According to verified document [{truth_record.source_id}], the {measurand_readable} "
                f"was measured at {truth_record.verified_value} {truth_record.unit}. The deterministic "
                f"verification passed against SOP {truth_record.sop_version}."
            )
        elif truth_record.decision == "flagged":
            question = (
                f"Why was {truth_record.experiment_id} flagged during {measurand_readable} analysis?"
            )
            explanation = (
                f"Document [{truth_record.source_id}] flagged {truth_record.experiment_id} because the "
                f"reported findings deviate from nominal bounds stipulated under SOP {truth_record.sop_version}. "
                f"Calculated value was {truth_record.verified_value} {truth_record.unit}."
            )
        else:
            question = f"What is the status of {truth_record.experiment_id} for {measurand_readable}?"
            explanation = (
                f"Data in [{truth_record.source_id}] remains inconclusive under SOP {truth_record.sop_version}. "
                "Insufficient evidence exists to certify a definitive quantity."
            )

        lab_notes = (
            f"Laboratory protocol {truth_record.sop_version}: Experiment {truth_record.experiment_id}. "
            f"Observed excerpt: \"{truth_record.evidence_text}\". "
            f"Governing conditions: {', '.join(truth_record.assumptions) if truth_record.assumptions else 'Standard ambient conditions'}."
        )

        target_response = {
            "decision": truth_record.decision,
            "measurand": truth_record.measurand,
            "correct_value": truth_record.verified_value,
            "unit": truth_record.unit,
            "explanation": explanation,
            "citations": [truth_record.source_id],
        }

        payload_to_hash = {
            "ledger_id": truth_record.ledger_id,
            "question": question,
            "lab_notes": lab_notes,
            "target": target_response,
            "generator": "deterministic_fixture_non_llm",
            "prompt_version": TEACHER_PROMPT_VERSION,
        }
        content_hash = fingerprint(payload_to_hash)

        return TeacherOutput(
            record_id=f"TCH-{truth_record.ledger_id}",
            ledger_id=truth_record.ledger_id,
            scenario_family=truth_record.scenario_family,
            candidate_question=question,
            lab_notes=lab_notes,
            explanation=explanation,
            evidence_spans=[truth_record.evidence_text],
            source_ids=[truth_record.source_id],
            target_response=target_response,
            metadata={
                "teacher_model_id": self.model_id,
                "teacher_revision": self.revision,
                "teacher_license": TEACHER_LICENSE,
                "prompt_version": TEACHER_PROMPT_VERSION,
                "mode": "fixture",
                "generator": "deterministic_fixture_non_llm",
                "sop_version": truth_record.sop_version,
                "created_at": now(),
            },
            content_hash=content_hash,
        )

    def _generate_endpoint(self, truth_record: TruthLedgerRecord) -> TeacherOutput:
        """Call external endpoint running Aya Expanse 8B on separate permitted compute."""
        if not self.endpoint_url:
            raise ValueError("endpoint_url is required when mode='endpoint'")

        prompt = (
            f"<|START_OF_TURN_TOKEN|><|SYSTEM_TOKEN|>You are a scientific dataset teacher. "
            f"Frame a precise lab question, notes, and explanation strictly adhering to the verified verdict.\n"
            f"VERIFIED RECORD:\n"
            f"Experiment: {truth_record.experiment_id}\n"
            f"Measurand: {truth_record.measurand}\n"
            f"Verified Value: {truth_record.verified_value} {truth_record.unit}\n"
            f"Decision: {truth_record.decision}\n"
            f"Source ID: {truth_record.source_id}\n"
            f"SOP: {truth_record.sop_version}\n"
            f"Evidence Excerpt: {truth_record.evidence_text}\n"
            f"DO NOT change the verified value or decision.<|END_OF_TURN_TOKEN|>\n"
            f"<|START_OF_TURN_TOKEN|><|USER_TOKEN|>Synthesize candidate question and lab notes.<|END_OF_TURN_TOKEN|>\n"
            f"<|START_OF_TURN_TOKEN|><|CHATBOT_TOKEN|>"
        )

        headers = {"Content-Type": "application/json"}
        if self.api_key:
            headers["Authorization"] = f"Bearer {self.api_key}"

        body = json.dumps({
            "model": self.model_id,
            "prompt": prompt,
            "max_tokens": 384,
            "temperature": 0.2,
            "stop": ["<|END_OF_TURN_TOKEN|>"],
        }).encode("utf-8")

        last_error = None
        for attempt in range(1, self.max_retries + 1):
            try:
                req = urllib.request.Request(self.endpoint_url, data=body, headers=headers, method="POST")
                with urllib.request.urlopen(req, timeout=self.timeout_seconds) as response:
                    res_body = json.loads(response.read().decode("utf-8"))
                    text = res_body.get("choices", [{}])[0].get("text", "") or res_body.get("text", "")
                    # Package structured output
                    return self._package_endpoint_output(truth_record, text)
            except Exception as e:
                last_error = e
                time.sleep(1.0 * attempt)

        raise RuntimeError(f"Teacher endpoint failed after {self.max_retries} attempts: {last_error}")

    def _package_endpoint_output(self, truth_record: TruthLedgerRecord, raw_completion: str) -> TeacherOutput:
        question = f"Analysis of {truth_record.experiment_id}: {truth_record.measurand} under {truth_record.sop_version}"
        target_response = {
            "decision": truth_record.decision,
            "measurand": truth_record.measurand,
            "correct_value": truth_record.verified_value,
            "unit": truth_record.unit,
            "explanation": raw_completion.strip(),
            "citations": [truth_record.source_id],
        }
        content_hash = fingerprint({"raw": raw_completion, "ledger_id": truth_record.ledger_id})
        return TeacherOutput(
            record_id=f"TCH-{truth_record.ledger_id}",
            ledger_id=truth_record.ledger_id,
            scenario_family=truth_record.scenario_family,
            candidate_question=question,
            lab_notes=raw_completion.strip(),
            explanation=raw_completion.strip(),
            evidence_spans=[truth_record.evidence_text],
            source_ids=[truth_record.source_id],
            target_response=target_response,
            metadata={
                "teacher_model_id": self.model_id,
                "teacher_revision": self.revision,
                "teacher_license": TEACHER_LICENSE,
                "prompt_version": TEACHER_PROMPT_VERSION,
                "mode": "endpoint",
                "sop_version": truth_record.sop_version,
                "created_at": now(),
            },
            content_hash=content_hash,
        )


def batch_generate_teacher_dataset(
    records: List[TruthLedgerRecord],
    client: TeacherClient,
    output_path: Optional[Path] = None,
) -> List[Dict[str, Any]]:
    """Batch generates teacher candidates from truth records and optionally persists an immutable manifest."""
    outputs = []
    for record in records:
        candidate = client.generate_candidate(record)
        outputs.append(asdict(candidate))

    if output_path:
        output_dir = output_path.parent
        output_dir.mkdir(parents=True, exist_ok=True)
        manifest = {
            "created_at": now(),
            "count": len(outputs),
            "teacher_model_id": client.model_id,
            "teacher_revision": client.revision,
            "mode": client.mode,
            "records_hash": fingerprint(outputs),
        }
        write_json(output_path, {"manifest": manifest, "candidates": outputs})

    return outputs


